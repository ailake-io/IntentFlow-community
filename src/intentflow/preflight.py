"""Evidence required before promoting a dbt build; never executes project code.

This checks a *full* build, not a selected sandbox build. Artifacts must be
generated by trusted CI in the candidate checkout. They are not signed proof.
"""
from __future__ import annotations

import json
import math
import time
from collections import Counter
from datetime import datetime
from pathlib import Path

from .i18n import tr
from .model import SEVERITIES

DEFAULT_REQUIRED = ("SQL001", "SQL002", "DBT002", "DBT003", "DBT004", "SCH001", "SCH002", "SCH003", "DBTR001", "DBTR002", "DBTR003", "BIZ001", "BIZ002")
SUPPORTED_REQUIRED = set(DEFAULT_REQUIRED) | {f"SQL{i:03}" for i in range(1, 16)} | {f"DBT{i:03}" for i in range(1, 6)} | {f"PRB{i:03}" for i in range(1, 5)} | {"CTR001", "DQ001"}
EXECUTABLE = {"model", "seed", "snapshot", "test", "unit_test"}


def inspect_artifacts(target, base, root, *, max_age_hours=24, warnings_as_errors=False, revision=None, require_freshness=False, now=None):
    """Return explicit gaps; missing, malformed and partial evidence cannot pass."""
    now = time.time() if now is None else now
    if not math.isfinite(max_age_hours) or max_age_hours <= 0:
        raise ValueError(tr("maximum artifact age must be a positive finite number"))
    if revision is not None and (not isinstance(revision, str) or not revision.strip()):
        raise ValueError(tr("expected artifact revision must not be empty"))
    report = {"errors": [], "warnings": [], "build_counts": {}, "expected_resources": 0, "revision": revision}

    def gap(code, message, nodes=()):
        report["errors"].append({"code": code, "message": str(message), "nodes": list(nodes)[:20], "total": len(nodes)})

    def read(folder, name, side):
        try:
            doc = json.loads((Path(folder) / name).read_text())
            if not isinstance(doc, dict) or not isinstance(doc.get("metadata"), dict):
                raise ValueError("expected an artifact object with metadata")
            return doc
        except (OSError, ValueError, UnicodeError) as e:
            gap("artifact_unavailable", tr("{side}/{name}: artifact unavailable or invalid ({error})", side=side, name=name, error=type(e).__name__))
            return None

    def nodes(man):
        sections = [man.get("nodes"), man.get("unit_tests", {})]
        if not all(isinstance(section, dict) and all(isinstance(n, dict) and isinstance(n.get("config", {}), dict)
                                                    for n in section.values()) for section in sections):
            raise ValueError("invalid manifest nodes")
        return {uid: n for section in sections for uid, n in section.items()
                if n.get("resource_type") in EXECUTABLE and (n.get("config") or {}).get("enabled", True)
                and (n.get("config") or {}).get("materialized") != "ephemeral"}

    documents = {}
    expected = {}
    def check_revision(doc, name):
        env = doc["metadata"].get("env")
        if revision and (not isinstance(env, dict) or env.get("INTENTFLOW_REVISION") != revision):
            gap("revision_mismatch", tr("{name}: artifact revision does not match the candidate", name=name))
    for side, folder in (("head", target), ("base", base)):
        man = read(folder, "manifest.json", side)
        cat = read(folder, "catalog.json", side)
        documents[side] = man
        if man:
            try:
                expected[side] = nodes(man)
            except (ValueError, TypeError, AttributeError):
                gap("manifest_invalid", tr("{side}: manifest resource definitions are invalid", side=side))
        if cat:
            if cat.get("errors"):
                gap("catalog_errors", tr("{side}: catalog generation reported errors", side=side))
            catalog_nodes = cat.get("nodes")
            if not isinstance(catalog_nodes, dict):
                gap("catalog_invalid", tr("{side}: catalog nodes are invalid", side=side))
            elif side in expected:
                missing = [uid for uid, n in expected[side].items() if n.get("resource_type") in {"model", "seed", "snapshot"}
                           and not (isinstance(catalog_nodes.get(uid), dict) and catalog_nodes[uid].get("columns"))]
                if missing:
                    gap("catalog_incomplete", tr("{side}: built relations are missing catalog columns", side=side), missing)
        if side == "head":
            for name, doc in (("manifest.json", man), ("catalog.json", cat)):
                if doc:
                    check_age(doc, name, now, max_age_hours, gap)
                    check_revision(doc, name)

    head, previous = documents.get("head"), documents.get("base")
    if report["errors"]:
        return report
    if head and previous:
        for key in ("project_name", "adapter_type"):
            h, b = head["metadata"].get(key), previous["metadata"].get(key)
            if not h or h != b:
                gap("baseline_mismatch", tr("base/head metadata differs or is absent: {key}", key=key))
        uncompiled = [uid for uid, n in expected.get("head", {}).items() if n.get("resource_type") in ("model", "snapshot")
                      and (n.get("language") or "sql") == "sql" and not n.get("compiled_code")]
        if uncompiled:
            gap("sql_not_compiled", tr("SQL models lack compiled code for required analysis"), uncompiled)

    built = read(target, "run_results.json", "head")
    if built:
        check_age(built, "run_results.json", now, max_age_hours, gap)
        check_revision(built, "run_results.json")
        if not isinstance(built.get("args"), dict) or built["args"].get("which") != "build":
            gap("build_required", tr("run_results must come from dbt build, not docs/parse/run/test"))
        rows = built.get("results")
        if not isinstance(rows, list) or not rows or any(not isinstance(r, dict) or not isinstance(r.get("unique_id"), str) for r in rows):
            gap("results_invalid", tr("build results are missing, empty or invalid"))
        else:
            ids = [r["unique_id"] for r in rows]
            counts = Counter(ids)
            repeated = [uid for uid, count in counts.items() if count > 1]
            if repeated:
                gap("results_duplicate", tr("build results repeat resource identifiers"), repeated)
            if "head" in expected:
                wanted = expected["head"]
                report["expected_resources"] = len(wanted)
                missing, extra = sorted(set(wanted) - set(ids)), sorted(set(ids) - set(wanted))
                if missing:
                    gap("build_incomplete", tr("full build evidence is missing resources"), missing)
                if extra:
                    gap("results_mismatch", tr("build results contain resources absent from the manifest"), extra)
                if not any(n.get("resource_type") in {"test", "unit_test"} for n in wanted.values()):
                    gap("tests_missing", tr("the manifest has no enabled tests"))
            statuses = Counter(str(r.get("status")) for r in rows)
            report["build_counts"] = dict(statuses)
            bad = [r["unique_id"] for r in rows if r.get("status") not in ("success", "pass", "warn")]
            if bad:
                gap("build_unsuccessful", tr("build contains failures, skipped resources or unknown statuses"), bad)
            warned = [r["unique_id"] for r in rows if r.get("status") == "warn"]
            if warned:
                if warnings_as_errors:
                    gap("build_warnings", tr("build warnings are blocking by policy"), warned)
                else:
                    report["warnings"].append({"code": "build_warnings", "nodes": warned[:20], "total": len(warned)})
            # dbt docs generates another invocation. Compare compiled content instead
            # of requiring invocation ids to match across those two commands.
            if head:
                all_nodes = head.get("nodes", {})
                drift = [r["unique_id"] for r in rows if isinstance(r.get("compiled_code"), str) and
                         isinstance(all_nodes.get(r["unique_id"], {}).get("compiled_code"), str) and
                         r["compiled_code"].strip() != all_nodes[r["unique_id"]]["compiled_code"].strip()]
                if drift:
                    gap("compiled_code_mismatch", tr("build and manifest compiled SQL differ"), drift)

    if head and require_freshness:
        sources = head.get("sources", {})
        freshness = read(target, "sources.json", "head")
        if freshness:
            check_age(freshness, "sources.json", now, max_age_hours, gap)
            check_revision(freshness, "sources.json")
            inspect_freshness(sources, freshness, now, warnings_as_errors, report, gap)

    if head:
        package = head["metadata"].get("project_name")
        changed = []
        for uid, n in head.get("nodes", {}).items() if isinstance(head.get("nodes"), dict) else []:
            if not isinstance(n, dict) or n.get("package_name") != package or not isinstance(n.get("raw_code"), str) or not n["raw_code"]:
                continue
            path = n.get("original_file_path", "")
            if Path(path).suffix.lower() not in {".sql", ".py"}:
                continue
            try:
                source = (Path(root) / path).resolve()
                if not source.is_relative_to(Path(root).resolve()) or source.read_text().strip() != n["raw_code"].strip():
                    changed.append(uid)
            except (OSError, UnicodeError):
                changed.append(uid)
        if changed:
            gap("source_changed", tr("current SQL/Python sources differ from the candidate manifest"), changed)
    return report


def inspect_freshness(sources, freshness, now, warnings_as_errors, report, gap):
    """Check all declared source SLAs; re-evaluate age at promotion time."""
    if not isinstance(sources, dict) or not sources or any(not isinstance(n, dict) for n in sources.values()):
        gap("source_freshness_missing", tr("source freshness requires declared sources and SLAs"))
        return
    rows = freshness.get("results")
    if not isinstance(rows, list) or any(not isinstance(r, dict) or not isinstance(r.get("unique_id"), str) for r in rows):
        gap("source_freshness_invalid", tr("source freshness results are invalid"))
        return
    by_id = {r["unique_id"]: r for r in rows}
    if len(by_id) != len(rows) or set(by_id) != set(sources):
        gap("source_freshness_incomplete", tr("source freshness did not evaluate exactly the declared sources"))
    periods = {"second": 1, "minute": 60, "hour": 3600, "day": 86400}
    for uid, source in sources.items():
        cfg = source.get("config") or {}
        if not isinstance(cfg, dict):
            gap("source_freshness_invalid", tr("source freshness timestamps or thresholds are invalid"), [uid])
            continue
        limits = cfg.get("freshness") if "freshness" in cfg else source.get("freshness")
        r = by_id.get(uid)
        if not isinstance(limits, dict) or not any(isinstance(limits.get(key), dict) and limits[key].get("count") is not None and limits[key].get("period") for key in ("warn_after", "error_after")):
            gap("source_sla_missing", tr("source has no freshness SLA"), [uid])
            continue
        if not r:
            continue
        if r.get("status") not in ("pass", "warn"):
            gap("source_freshness_failed", tr("source freshness failed or could not execute"), [uid])
            continue
        try:
            loaded = datetime.fromisoformat(r["max_loaded_at"].replace("Z", "+00:00"))
            snapshot = datetime.fromisoformat(r["snapshotted_at"].replace("Z", "+00:00"))
            if loaded.tzinfo is None or snapshot.tzinfo is None or snapshot.timestamp() > now + 300 or loaded.timestamp() > snapshot.timestamp() + 300:
                raise ValueError("invalid timezone/clock")
            age = now - loaded.timestamp()
            if age < -300:
                raise ValueError("future loaded timestamp")
            warned = r["status"] == "warn"
            for key in ("warn_after", "error_after"):
                limit = limits.get(key)
                if not limit or (isinstance(limit, dict) and limit.get("count") is None and limit.get("period") is None):
                    continue
                count, unit = float(limit["count"]), limit["period"]
                if not math.isfinite(count) or count < 0 or unit not in periods:
                    raise ValueError("invalid threshold")
                if age > count * periods[unit]:
                    if key == "error_after":
                        gap("source_stale", tr("source data exceeds its freshness SLA at promotion time"), [uid])
                    else:
                        warned = True
            if warned:
                if warnings_as_errors:
                    gap("source_freshness_warning", tr("source freshness warning blocks by policy"), [uid])
                else:
                    report["warnings"].append({"code": "source_freshness_warning", "nodes": [uid]})
        except (KeyError, TypeError, ValueError, AttributeError, OverflowError):
            gap("source_freshness_invalid", tr("source freshness timestamps or thresholds are invalid"), [uid])


def inspect_quality(spec, project, now, hours, warnings_as_errors, report):
    """Require recognized, current and mapped GX/Soda results for every input."""
    from . import dq_results
    from .checks.dq import _index, _match
    def gap(code, message):
        report["errors"].append({"code": code, "message": str(message)})
    parts = [part.strip() for part in (spec or "").split(",") if part.strip()]
    if not parts:
        gap("quality_required", tr("required external quality results are not configured"))
    index = _index(project)
    def payloads(doc):
        if isinstance(doc, list):
            for item in doc:
                yield from payloads(item)
        elif isinstance(doc, dict) and "run_results" in doc:
            for item in doc["run_results"].values():
                yield from payloads(item.get("validation_result", item))
        else:
            yield doc
    for part in parts:
        files = dq_results.expand(part)
        if not files:
            gap("quality_required", tr("required external quality input is missing: {path}", path=part))
        for file in files:
            try:
                doc = json.loads(file.read_text())
                items = list(payloads(doc))
                if not items:
                    raise ValueError("empty results")
                for item in items:
                    parsed = dq_results.parse(item)
                    if not parsed or item.get("hasErrors") or any(r.status == "error" for r in parsed):
                        raise ValueError("unrecognized or incomplete results")
                    meta = item.get("meta") or {}
                    stamp = item.get("scanStartTimestamp") or meta.get("validation_time") or (meta.get("run_id") or {}).get("run_time")
                    check_age({"metadata": {"generated_at": stamp}}, str(file), now, hours,
                              lambda code, message: gap(code, message))
                    if any(_match(index, r.table, strict=True) is None for r in parsed):
                        gap("quality_unmapped", tr("external quality results do not map unambiguously to project models"))
                    if warnings_as_errors and any(r.status == "warn" for r in parsed):
                        gap("quality_warning", tr("external quality warnings block by policy"))
            except (OSError, ValueError, KeyError, TypeError, AttributeError, UnicodeError):
                gap("quality_required", tr("external quality input is invalid or incomplete: {path}", path=file))


def check_age(doc, name, now, hours, gap):
    try:
        stamp = datetime.fromisoformat(doc["metadata"]["generated_at"].replace("Z", "+00:00"))
        if stamp.tzinfo is None:
            raise ValueError("missing timezone")
        age = now - stamp.timestamp()
        if age < -300 or age > hours * 3600:
            gap("artifact_stale", tr("{name}: timestamp is stale or in the future", name=name))
    except (KeyError, TypeError, ValueError, AttributeError, OverflowError):
        gap("artifact_timestamp", tr("{name}: generated_at must include a valid timezone", name=name))


def run(store, options, *, required=(), max_age_hours=24, warnings_as_errors=False, fail_on="high", revision=None, require_freshness=False):
    from . import runner
    from .checks import REGISTRY, load_all

    o = runner.resolve_options(store, options)
    if not all(o.get(k) for k in ("target", "base", "root")):
        raise ValueError(tr("preflight requires target, base and root"))
    evidence = inspect_artifacts(o["target"], o["base"], o["root"], max_age_hours=max_age_hours, warnings_as_errors=warnings_as_errors, revision=revision, require_freshness=require_freshness)
    evidence.update({"ok": False, "findings": [], "completed_checks": [], "failed_checks": [], "required_checks": sorted(set(DEFAULT_REQUIRED) | set(required))})
    load_all()
    known = {code for c in REGISTRY.values() for code in (c.id, *c.emits)}
    unknown = set(evidence["required_checks"]) - known
    if unknown:
        evidence["errors"].append({"code": "unknown_checks", "message": str(tr("unknown required checks")), "nodes": sorted(unknown)})
    unsupported = set(required) & known - SUPPORTED_REQUIRED
    if unsupported:
        evidence["errors"].append({"code": "unsupported_required_evidence", "message": str(tr("mandatory input evidence is not supported for these checks")), "nodes": sorted(unsupported)})
    if "DQ001" in required and not evidence["errors"]:
        from . import dbt_loader
        inspect_quality(store.get_setting("dq.results"), dbt_loader.load(o["target"], o["root"]), time.time(), max_age_hours, warnings_as_errors, evidence)
    if "CTR001" in required:
        from . import contracts
        try:
            contracts.load_all(store.get_setting("contracts.dir"), strict=True)
        except Exception:
            evidence["errors"].append({"code": "contracts_required", "message": str(tr("required contracts must be configured and readable"))})
    warehouse_required = {"PRB001", "PRB002", "PRB003", "PRB004", "SQL012", "SQL013", "SQL014"} & set(required)
    if warehouse_required:
        from . import warehouses
        wh = None
        try:
            wh = warehouses.connect(lambda key: o.get("duckdb") or store.get_setting(key) if key == "warehouse.duckdb" else
                                    o.get("postgres_env") or store.get_setting(key) if key == "warehouse.postgres_env" else store.get_setting(key))
            if wh is None:
                raise ValueError("warehouse not configured")
        except Exception:
            evidence["errors"].append({"code": "warehouse_required", "message": str(tr("required warehouse checks need an available connection")), "nodes": sorted(warehouse_required)})
        finally:
            if wh is not None:
                wh.close()
    # Do not load malformed or partial artifacts into the normal runner/store.
    if evidence["errors"]:
        return evidence
    try:
        result = runner.run_check(store, o, required_checks=set(evidence["required_checks"]))
    except Exception as e:
        evidence["errors"].append({"code": "checks_unavailable", "message": str(tr("preflight checks unavailable ({error})", error=type(e).__name__))})
        return evidence
    evidence["completed_checks"] = result["completed_checks"]
    evidence["failed_checks"] = result["failed_checks"]
    missing = sorted(set(evidence["required_checks"]) - set(result["completed_checks"]))
    if missing or result["failed_checks"]:
        evidence["errors"].append({"code": "checks_incomplete", "message": str(tr("required checks did not complete or a check failed")),
                                   "nodes": sorted(set(missing) | set(result["failed_checks"]))})
    evidence["findings"] = [f.to_dict() for f in result["findings"]]
    evidence["lineage"] = result["lineage"]
    levels = SEVERITIES[:SEVERITIES.index(fail_on) + 1]
    evidence["blocking_findings"] = [f.id for f in result["findings"] if f.severity in levels]
    evidence["ok"] = not evidence["errors"] and not evidence["blocking_findings"]
    return evidence
